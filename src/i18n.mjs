export function locale() {
  let language;
  try { language = globalThis.Zotero?.Prefs?.get("quickswitcher.language"); } catch { /* Use the host locale when preferences are not ready. */ }
  if (!["en-US", "zh-CN"].includes(language)) language = globalThis.Zotero?.locale || globalThis.Services?.locale?.appLocaleAsBCP47 || "zh-CN";
  return /^zh(?:-|$)/iu.test(language) ? "zh-CN" : "en-US";
}

const reverse = new Map(Object.entries(english).map(([source, text]) => [text, source]));
const templates = Object.entries(english).filter(([source]) => /\{\w+\}/u.test(source)).flatMap(([source, translated]) =>
  [source, translated].map(text => {
    const names = [], parts = text.split(/(\{\w+\})/u);
    const pattern = parts.map(part => /^\{\w+\}$/u.test(part) ? (names.push(part.slice(1, -1)), "([\\s\\S]*?)") : part.replace(/[.*+?^${}()|[\]\\]/gu, "\\$&")).join("");
    return { source, names, pattern: new RegExp("^" + pattern + "$") };
  }));

export function t(message, values = {}) {
  let source = String(message), parameters = values;
  if (!Object.hasOwn(english, source)) {
    const original = reverse.get(source);
    if (original) source = original;
    else for (const template of templates) {
      const match = source.match(template.pattern);
      if (!match) continue;
      source = template.source; parameters = { ...Object.fromEntries(template.names.map((name, index) => [name, match[index + 1]])), ...values }; break;
    }
  }
  const isEnglish = locale() === "en-US";
  let text = isEnglish && Object.hasOwn(english, source) ? english[source] : source;
  if (isEnglish && Number(parameters.count) === 1) text = text.replace("{count} items", "{count} item");
  return String(text).replace(/\{(\w+)\}/gu, (match, name) => Object.hasOwn(parameters, name) ? String(parameters[name]) : match);
}

export function localize(node, messages) {
  node.qsL10n = messages; node.setAttribute("data-qs-l10n", "");
  for (const [attribute, message] of Object.entries(messages)) {
    const text = Array.isArray(message) ? t(message[0], message[1]) : t(message);
    if (attribute === "text") node.textContent = text;
    else if (attribute === "value") node.value = text;
    else node.setAttribute(attribute, text);
  }
  return node;
}

export function refreshTranslations(doc) {
  for (const node of doc.querySelectorAll("[data-qs-l10n]")) if (node.qsL10n) localize(node, node.qsL10n);
}
